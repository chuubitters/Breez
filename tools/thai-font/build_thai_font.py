"""
สร้างฟอนต์ "Breez Thai" จาก Prompt Regular ให้แสดงภาษาไทยถูกต้องใน Unity TextMeshPro
(TMP ไม่รองรับ GPOS/GSUB: วรรณยุกต์ซ้อนสระบน / พยัญชนะหางยาว จะทับกัน)
- shape ทุกคลัสเตอร์ พยัญชนะ+สระบน/ล่าง+วรรณยุกต์(+ำ) ด้วย HarfBuzz
- glyph ที่ต้องเลื่อน/เปลี่ยนรูป => สร้าง composite glyph ที่เลื่อนไว้แล้ว ใส่ใน PUA (U+F700..)
- เขียนตาราง C# (ต้นฉบับ -> ข้อความที่แทน PUA แล้ว) ให้ ThaiShaper ใช้
"""
import sys, itertools
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.ttLib.tables._g_l_y_f import Glyph, GlyphComponent

src, out_font, out_cs = sys.argv[1], sys.argv[2], sys.argv[3]
tt = TTFont(src)
order = list(tt.getGlyphOrder())
cmap = tt.getBestCmap()
rev = {}
for cp, g in cmap.items(): rev.setdefault(g, cp)

blob = hb.Blob.from_file_path(src); face = hb.Face(blob); font = hb.Font(face)
def shape(s):
    buf = hb.Buffer(); buf.add_str(s); buf.guess_segment_properties(); hb.shape(font, buf, {})
    return [(order[i.codepoint], p.x_advance, p.x_offset, p.y_offset) for i, p in zip(buf.glyph_infos, buf.glyph_positions)]

hmtx = tt['hmtx']
consonants = [chr(c) for c in range(0x0E01, 0x0E2F)]
lower = ['', 'ุ', 'ู', 'ฺ']
upper = ['', 'ั', 'ิ', 'ี', 'ึ', 'ื', '็', 'ํ']
tones = ['', '่', '้', '๊', '๋', '์']
am = ['', 'ำ']

pua_next = 0xF700
pua_of = {}            # (glyph, dx, dy, adv) -> codepoint
new_glyphs = []        # (name, src glyph, dx, dy, adv)
table = {}

def char_for(g, adv, dx, dy):
    global pua_next
    # ถ้าเป็น glyph ปกติของตัวอักษรนั้นและไม่เลื่อน ใช้ตัวอักษรเดิม
    if dx == 0 and dy == 0 and g in rev and hmtx[g][0] == adv:
        return chr(rev[g])
    key = (g, dx, dy, adv)
    if key not in pua_of:
        if pua_next > 0xF8FF: raise SystemExit('PUA full')
        name = f'breez.{pua_next:04X}'
        pua_of[key] = pua_next
        new_glyphs.append((name, g, dx, dy, adv, pua_next))
        pua_next += 1
    return chr(pua_of[key])

for c in consonants:
    combos = set()
    for l, u, t, a in itertools.product(lower, upper, tones, am):
        if l and u: continue
        if a and (l or u): continue
        s = c + l + u + t + a
        if len(s) > 1: combos.add(s)
    for s in sorted(combos):
        out = ''.join(char_for(g, adv, dx, dy) for g, adv, dx, dy in shape(s))
        if out != s: table[s] = out

# ---------- เพิ่ม glyph ลงฟอนต์ ----------
glyf = tt['glyf']
for name, g, dx, dy, adv, cp in new_glyphs:
    comp = GlyphComponent()
    comp.glyphName = g
    comp.x, comp.y = dx, dy
    comp.flags = 0x4   # ROUND_XY_TO_GRID (ARGS_ARE_XY_VALUES ถูกตั้งตอน compile)
    glyph = Glyph()
    glyph.numberOfContours = -1
    glyph.components = [comp]
    glyf[name] = glyph
    order.append(name)
tt.setGlyphOrder(order)
for name, g, dx, dy, adv, cp in new_glyphs:
    glyf[name].recalcBounds(glyf)
    hmtx[name] = (adv, getattr(glyf[name], 'xMin', 0))
    for sub in tt['cmap'].tables:
        if sub.isUnicode(): sub.cmap[cp] = name
if 'post' in tt and tt['post'].formatType == 2.0:
    tt['post'].extraNames = []
    tt['post'].mapping = {}

# ---------- เปลี่ยนชื่อฟอนต์ ----------
for rec in tt['name'].names:
    if rec.nameID in (1, 16): rec.string = 'Breez Thai'
    elif rec.nameID == 4: rec.string = 'Breez Thai Regular'
    elif rec.nameID == 6: rec.string = 'BreezThai-Regular'
    elif rec.nameID == 3: rec.string = 'BreezThai-Regular (based on Prompt)'
tt.save(out_font)

# ---------- ตาราง C# ----------
def lit(s): return '"' + ''.join(f'\\u{ord(ch):04X}' for ch in s) + '"'
keys = sorted(table)
with open(out_cs, 'w', encoding='utf-8') as f:
    f.write('// <auto-generated> สร้างจาก build_thai_font.py (Prompt Regular + HarfBuzz) ห้ามแก้ด้วยมือ </auto-generated>\n')
    f.write('// คลัสเตอร์ภาษาไทย -> glyph ที่จัดตำแหน่งไว้แล้วใน PUA ของฟอนต์ Breez Thai\n')
    f.write('internal static class ThaiShapingTable\n{\n')
    f.write(f'    internal const int Count = {len(keys)};\n')
    f.write('    internal static readonly string[] Keys =\n    {\n')
    for i in range(0, len(keys), 8): f.write('        ' + ', '.join(lit(k) for k in keys[i:i+8]) + ',\n')
    f.write('    };\n    internal static readonly string[] Values =\n    {\n')
    for i in range(0, len(keys), 8): f.write('        ' + ', '.join(lit(table[k]) for k in keys[i:i+8]) + ',\n')
    f.write('    };\n}\n')
print(f'clusters remapped: {len(table)}, new PUA glyphs: {len(new_glyphs)} (U+F700..U+{pua_next-1:04X})')
